const fs = require('fs');
const assert = require('node:assert/strict');
const { PGlite } = require('@electric-sql/pglite');
(async () => {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create table public.stories(id uuid primary key,user_id uuid references auth.users(id),title text,form jsonb,chapters jsonb,messages jsonb,story_state jsonb,custom_rewrite text,updated_at timestamptz);
    grant all on public.stories to service_role;
  `);
  await db.exec(fs.readFileSync('supabase/migrations/20261027152347_story_background_generation.sql','utf8'));
  const owner = '11111111-1111-4111-8111-111111111111';
  const other = '22222222-2222-4222-8222-222222222222';
  const story = '33333333-3333-4333-8333-333333333333';
  const job = '44444444-4444-4444-8444-444444444444';
  await db.query('insert into auth.users values ($1),($2)', [owner,other]);
  await db.query("insert into stories values ($1,$2,'Original','{}','[]','[]','{}','original draft','2026-10-27T12:00:00Z')", [story,owner]);
  const result = { story: { id: story, title:'Generated',storyBible:{},chapters:[],messages:[],storyState:{} },pending:{ storyId:story,draft:'Recovered draft' } };
  await db.query("insert into story_generation_jobs(id,story_id,user_id,input,source_updated_at,result) values($1,$2,$3,'{}','2026-10-27T12:00:00Z',$4)", [job,story,owner,JSON.stringify(result)]);
  await db.exec('set role service_role');
  await db.query('select finish_story_generation_job($1)',[job]);
  await db.exec('reset role');
  let saved = (await db.query('select title,custom_rewrite from stories')).rows[0];
  assert.equal(saved.title,'Generated');
  assert.equal(JSON.parse(saved.custom_rewrite).draft,'Recovered draft');
  assert.equal((await db.query('select status from story_generation_jobs')).rows[0].status,'completed');
  await db.query('select finish_story_generation_job($1)',[job]);
  assert.equal((await db.query('select title from stories')).rows[0].title,'Generated','Finalization is idempotent');
  const conflict = '55555555-5555-4555-8555-555555555555';
  await db.query("insert into story_generation_jobs(id,story_id,user_id,input,source_updated_at,result) values($1,$2,$3,'{}','2026-10-27T12:00:00Z',$4)",[conflict,story,owner,JSON.stringify(result)]);
  await db.exec("update stories set title='Newer manual edit'");
  await db.query('select finish_story_generation_job($1)',[conflict]);
  assert.equal((await db.query('select title from stories')).rows[0].title,'Newer manual edit');
  assert.equal((await db.query('select status from story_generation_jobs where id=$1',[conflict])).rows[0].status,'conflict');
  await db.exec('set role authenticated');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[other]);
  assert.equal((await db.query('select * from story_generation_jobs')).rows.length,0);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[owner]);
  assert.equal((await db.query('select * from story_generation_jobs')).rows.length,2);
  await assert.rejects(db.query('update story_generation_jobs set status=\'completed\''));
  await assert.rejects(db.query('select finish_story_generation_job($1)',[job]));
  await db.exec('reset role');
  await db.close();
  console.log('PASS: migration, owner-only reads, client writes/RPC denied, service-role persistence, preserved pending draft, idempotent finalization and concurrent-edit protection.');
})().catch(error=>{ console.error(error);process.exitCode=1; });
